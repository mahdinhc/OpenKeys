// Packs plugins/templates/*.js into src/pluginTemplates.ts (shown in the app under Plugins -> Bootstrap).
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..'), dir = path.join(root, 'plugins', 'templates');
const list = fs.readdirSync(dir).filter((f) => f.endsWith('.js')).sort().map((f) => {
  const code = fs.readFileSync(path.join(dir, f), 'utf8');
  const name = (code.match(/name:\s*"([^"]+)"/) || [])[1] || f;
  const description = (code.match(/description:\s*"([^"]+)"/) || [])[1] || '';
  const title = (code.match(/^\/\/\s*([^—\n]+?)\s*—\s*(.*)$/m) || []);
  return {id: f.replace(/^\d+-/, '').replace(/\.js$/, ''), title: title[1] || name, about: title[2] || description, code};
});
fs.writeFileSync(path.join(root, 'src', 'pluginTemplates.ts'),
  '// GENERATED by scripts/gen_plugin_templates.js from plugins/templates/*.js - do not edit.\n' +
  'export type PluginTemplate = {id: string; title: string; about: string; code: string};\n' +
  'export const PLUGIN_TEMPLATES: PluginTemplate[] = ' + JSON.stringify(list, null, 2) + ';\n');
console.log('templates:', list.map((t) => t.id).join(', '));
